import Foundation

/// 还在成型中的功能。
///
/// 默认全关。放在这里的东西有一个共同点:**它们的数据模型还会变**。
/// 提前开给所有人,等于给自己攒下一堆将来必须迁移的数据,
/// 而那些数据在功能成型前几乎没有价值。
///
/// 开关只控制入口是否出现,不删数据——自己打开测试过的人,
/// 下个版本回来时东西还在。
enum ExperimentalFeatures {
  /// 工作台:一件创作从灵感到成品的加工区。
  ///
  /// v1 关闭的具体理由:现在它的正文直接存成一条笔记,混在「我的笔记」里。
  /// 三模块(输入/工作台/输出)切开之后这个模型要改,已经建的数据都得迁。
  /// 而当前版本的工作台还没有 AI,手动建创作的价值不足以抵消迁移成本。
  static let workbenchKey = "experimental.workbench.enabled"
}
