import SwiftUI

extension View {
  /// 在超长的视图类型中间断一刀。
  ///
  /// 同一个模块里的 `some View` 会被编译器展开成真实类型：详情页、主窗口、设置页这种几千行的
  /// 视图，最后各是一个几万字符长、套了几十层的泛型类型。App 第一次画它时，Swift 运行时要把
  /// 类型名逐层解出来、逐层求一遍协议表，耗时随套的层数平方增长——2026-10-16 测速：启动时主线程
  /// 约九成时间耗在这里，第一次出现的详情页卡 1.2 秒、设置页卡 0.3 秒。
  ///
  /// 在大块子树外面、长修饰链中间包一层 AnyView，后面的类型名里就只剩 `AnyView`，各段分开解，
  /// 总量降到原来的零头。只包在结构不随数据换类型的大块外层：AnyView 换了里面的具体类型才会
  /// 重建子树，这里每处包的都是固定类型，界面状态和动画不受影响。
  func typeErased() -> AnyView { AnyView(self) }
}
